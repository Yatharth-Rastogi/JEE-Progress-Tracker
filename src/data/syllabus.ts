/**
 * Safely merges loaded/cached chapters with MASTER_SYLLABUS,
 * guaranteeing 100% unique chapter IDs, correct authoritative JEE priorities,
 * and preserving all user practice & theory progress.
 */
export function mergeLoadedChaptersWithMaster(loadedChapters: Chapter[]): Chapter[] {
  if (!Array.isArray(loadedChapters) || loadedChapters.length === 0) {
    return JSON.parse(JSON.stringify(MASTER_SYLLABUS));
  }

  const normalize = (str: string) => (str || '').toLowerCase().replace(/[^a-z0-9]/g, '');

  return MASTER_SYLLABUS.map((masterCh) => {
    // 1. First try matching by exact name
    let match = loadedChapters.find(
      (c) => c.name && c.name.trim().toLowerCase() === masterCh.name.trim().toLowerCase()
    );

    // 2. Try normalized name match
    if (!match) {
      const masterNorm = normalize(masterCh.name);
      match = loadedChapters.find((c) => {
        if (!c.name) return false;
        const cNorm = normalize(c.name);
        return masterNorm.includes(cNorm) || cNorm.includes(masterNorm);
      });
    }

    // 3. If loadedChapters is from the same 67-chapter version, try matching by id
    if (!match && loadedChapters.length === MASTER_SYLLABUS.length) {
      match = loadedChapters.find((c) => c.id === masterCh.id);
    }

    // 4. Fallback matching by id only if subject matches
    if (!match) {
      match = loadedChapters.find((c) => c.id === masterCh.id && c.subject === masterCh.subject);
    }

    if (match) {
      const validUrl = getValidVideoUrlForChapter(masterCh.id, match.videoUrl || masterCh.videoUrl);
      return {
        ...masterCh,
        theoryStatus: match.theoryStatus || masterCh.theoryStatus,
        theoryPercent: typeof match.theoryPercent === 'number' ? match.theoryPercent : masterCh.theoryPercent,
        basicAttempted: typeof match.basicAttempted === 'number' ? match.basicAttempted : masterCh.basicAttempted,
        basicCorrect: typeof match.basicCorrect === 'number' ? match.basicCorrect : masterCh.basicCorrect,
        pyqAttempted: typeof match.pyqAttempted === 'number' ? match.pyqAttempted : masterCh.pyqAttempted,
        pyqCorrect: typeof match.pyqCorrect === 'number' ? match.pyqCorrect : masterCh.pyqCorrect,
        genuineSolves: typeof match.genuineSolves === 'number' ? match.genuineSolves : masterCh.genuineSolves,
        guessAttempts: typeof match.guessAttempts === 'number' ? match.guessAttempts : masterCh.guessAttempts,
        guessCorrect: typeof match.guessCorrect === 'number' ? match.guessCorrect : masterCh.guessCorrect,
        guessWrong: typeof match.guessWrong === 'number' ? match.guessWrong : masterCh.guessWrong,
        revision1: Boolean(match.revision1),
        revision2: Boolean(match.revision2),
        revision3: Boolean(match.revision3),
        videoCurrentTime: typeof match.videoCurrentTime === 'number' ? match.videoCurrentTime : masterCh.videoCurrentTime,
        videoDuration: typeof match.videoDuration === 'number' ? match.videoDuration : masterCh.videoDuration,
        videoUrl: validUrl,
        videoTitle: match.videoTitle || masterCh.videoTitle,
        bookmarks: Array.isArray(match.bookmarks) ? match.bookmarks : (masterCh.bookmarks || []),
        theoryNotes: typeof match.theoryNotes === 'string' ? match.theoryNotes : (masterCh.theoryNotes || ''),
        // Crucial: ALWAYS enforce masterCh identifiers so React keys are 100% unique
        id: masterCh.id,
        subject: masterCh.subject,
        unit: masterCh.unit,
        name: masterCh.name,
        priority: masterCh.priority,
        strategicTier: masterCh.strategicTier,
        historicalWeightage: masterCh.historicalWeightage,
        avgQsPerShift: masterCh.avgQsPerShift,
        prerequisites: masterCh.prerequisites,
      };
    }

    return {
      ...masterCh,
      videoUrl: getValidVideoUrlForChapter(masterCh.id, masterCh.videoUrl),
      bookmarks: masterCh.bookmarks || [],
      theoryNotes: masterCh.theoryNotes || '',
    };
  });
}
